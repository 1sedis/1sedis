/** The chronicle entry for a game (game 2 shows LORE[0]); later games repeat the last one. */
export function loreForGame(game: number): LoreEntry | null {
  if (game < 2) return null;
  return LORE[Math.min(game - 2, LORE.length - 1)];
}
